export let language = "en";
export function setLanguage(value) { language = value === "zh" ? "zh" : "en"; }
export function t(source, ...values) {
  const key = Array.isArray(source) ? source.reduce((result, part, index) => result + (index ? `{${index - 1}}` : "") + part, "") : source;
  const text = language === "zh" || !Object.hasOwn(translations, key) ? key : translations[key];
  return values.length ? text.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match) : text;
}

export function localizedError(message, status = 0) {
  if (language === "zh" || !/[\u3400-\u9fff]/.test(message)) return message;
  if (Object.hasOwn(translations, message)) return t(message);
  const guidance = {
    401: "Sign-in or authorization failed. Check your credentials and email verification.",
    402: "Available credit or budget is insufficient. Review both before another request.",
    403: "This action is not permitted. Check account status, verification, and service availability.",
    404: "Record not found. An original request may still be in flight; do not automatically create another purchase or model request.",
    409: "The request conflicts with existing state. Look up the original request before taking another action.",
    422: "Check the required fields, formats, and configured limits.",
    429: "Rate limit reached. Wait before retrying; preserve the original request ID.",
  };
  return `${guidance[status] || "The request could not be confirmed. Check its status or contact support."} (HTTP ${status || "unknown"})`;
}

// Capture only the initial, known UI copy. Never walk customer-created nodes
// after login, so a key name or model answer matching a label stays untouched.
export function captureStaticLocale(root = document) {
  const bindings = [];
  const walker = root.createTreeWalker(root.documentElement, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest("script, style, [data-no-translate]")) continue;
    const key = node.textContent.trim();
    if (Object.hasOwn(translations, key)) bindings.push({node, key, original: node.textContent});
  }
  root.querySelectorAll("[aria-label], [placeholder]").forEach((element) => {
    for (const attribute of ["aria-label", "placeholder"]) {
      const key = element.getAttribute(attribute);
      if (key && Object.hasOwn(translations, key)) bindings.push({node: element, key, attribute});
    }
  });
  return () => {
    root.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    for (const binding of bindings) {
      if (!binding.node.isConnected) continue;
      if (binding.attribute) binding.node.setAttribute(binding.attribute, t(binding.key));
      else binding.node.textContent = binding.original.replace(binding.key, () => t(binding.key));
    }
  };
}
